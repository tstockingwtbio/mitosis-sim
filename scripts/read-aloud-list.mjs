// Lists every piece of text the sim can read aloud, the recording file it
// looks for, and whether that file exists yet. Writes docs/read-aloud-script.md.
//   npm run audio:list
import fs from 'node:fs';

const content = JSON.parse(fs.readFileSync('src/content/partA.json', 'utf8'));
const en = JSON.parse(fs.readFileSync('src/i18n/en.json', 'utf8'));

const slug = (key) => key.replace(/[^A-Za-z0-9]+/g, '-');
const fileFor = (key, level) => `mm_txt_${slug(key)}_en_${level}.mp3`;
const has = (dir, f) => fs.existsSync(`public/audio/${dir}/${f}`);
const levels = (entry) => (typeof entry === 'object' ? ['building', ...(entry.beginning ? ['beginning'] : [])] : ['building']);
const text = (entry, level) => (typeof entry === 'string' ? entry : entry[level] ?? entry.building);

/** Keys in the order a student meets them, with where each is used. */
const seen = new Map();
const add = (key, where) => {
  if (!(key in en)) throw new Error(`missing key ${key}`);
  if (!seen.has(key)) seen.set(key, where);
};
const dynamic = [];

const ZOOM = ['fig', 'tissue', 'cell', 'nucleus', 'chromosome', 'gene', 'dna'];
// Shared feedback pieces.
add('ui.task.correct', 'Feedback (all checks)');
add('ui.task.notYet', 'Feedback (all checks)');
add('ui.task.mixup', 'Feedback (all checks)');

for (const beat of content.beats.filter((b) => b.built)) {
  for (const step of beat.steps) {
    const where = `${beat.id} · ${step.id}`;
    if (step.type === 'explain') {
      step.body.forEach((k) => add(k, where));
      if (step.scene === 'zoom-ladder') ZOOM.forEach((r) => add(`A1.zoom.${r}.text`, `${where} (zoom level)`));
    } else if (step.type === 'intro' || step.type === 'summary') {
      step.body.forEach((k) => add(k, where));
      if (step.type === 'summary') dynamic.push(['ui.summary.score', where]);
    } else if (step.type === 'retrieve') {
      add('ui.retrieve.intro', where);
      step.tasks.forEach((id) => add(content.tasks[id].prompt, `${where} (${id})`));
    } else if (step.type === 'task') {
      const ids = [step.task, content.tasks[step.task].goFurther].filter(Boolean);
      for (const id of ids) {
        const task = content.tasks[id];
        const w = `${where} (${id}${task.isGoFurther ? ', Go further' : ''})`;
        add(task.prompt, w);
        (task.worked ?? []).forEach((k) => add(k, `${w} worked step`));
        if (task.phase !== 'checkpoint') (task.hints ?? []).forEach((k) => add(k, `${w} hint`));
        if (task.kind === 'predict' && task.frames) add(task.frames, `${w} sentence starter`);
        for (const r of task.feedback ?? []) {
          add(r.text, `${w} feedback`);
          if (r.misconception) add(content.misconceptions[r.misconception], `${w} mix-up`);
        }
        for (const o of task.options ?? []) {
          add(o.text, `${w} choice`);
          add(o.feedback, `${w} choice feedback`);
          if (o.misconception) add(content.misconceptions[o.misconception], `${w} mix-up`);
        }
        if (task.phase === 'checkpoint') add('ui.task.firstTry', w);
        if (task.kind === 'pair') add('ui.task.revealPairs', `${w} (after 3 tries)`);
        if (task.kind === 'count') dynamic.push(['ui.task.revealCount', `${w} (after 3 tries)`]);
      }
    }
  }
}

const rows = [];
let need = { building: 0, beginning: 0 };
let done = 0;
for (const [key, where] of seen) {
  for (const level of levels(en[key])) {
    const file = fileFor(key, level);
    const ok = has('txt', file);
    if (ok) done++;
    else need[level]++;
    rows.push({ key, level, file, ok, where, text: text(en[key], level) });
  }
}

const esc = (s) => String(s).replace(/\|/g, '\\|');
const table = (list) =>
  ['| Status | File | Text | Where |', '| --- | --- | --- | --- |', ...list.map((r) => `| ${r.ok ? '✓ recorded' : '**needed**'} | \`${r.file}\` | ${esc(r.text)} | ${esc(r.where)} |`)].join('\n');

// Story narration (voice-over) status, for completeness.
const voRows = Object.keys(en)
  .filter((k) => k.startsWith('vo.'))
  .map((k) => {
    const id = k.slice(3);
    const file = `mm_vo_${id.replace('VO-', '')}_en_building.mp3`;
    return { id, file, ok: has('vo', file) };
  });

const md = `# Read-aloud recording list

Generated by \`npm run audio:list\` on ${new Date().toISOString().slice(0, 10)}. Re-run it after adding files to see what is left.

The sim reads two kinds of text aloud:

- **Story narration** (captions): the voice-over lines in the story bible, files in \`public/audio/vo/\`.
- **Panel text** (the 🔊 button on the panel, plus feedback, hints and worked steps as they appear): files in \`public/audio/txt/\`, named \`mm_txt_<text key>_<language>_<level>.mp3\`.

Anything without a recording is read by the browser's built-in voice, so nothing breaks while files are missing.

## Summary

- Story narration: ${voRows.filter((r) => r.ok).length} of ${voRows.length} recorded.
- Panel text, Building (English): ${rows.filter((r) => r.level === 'building' && r.ok).length} of ${rows.filter((r) => r.level === 'building').length} recorded; **${need.building} needed**.
- Panel text, Beginning (English): ${rows.filter((r) => r.level === 'beginning' && r.ok).length} of ${rows.filter((r) => r.level === 'beginning').length} recorded; **${need.beginning} needed**. Only used when a student picks the Beginning support level in English.

Record each line exactly as written. You can add ElevenLabs direction tags to the text you paste in; the captions are not affected.

## Panel text: Building

${table(rows.filter((r) => r.level === 'building'))}

## Panel text: Beginning

${table(rows.filter((r) => r.level === 'beginning'))}

## Always read by the browser voice

These contain numbers that change for each student, so they cannot be pre-recorded:

${dynamic.filter((d, i, a) => a.findIndex((x) => x[0] === d[0]) === i).map(([k, w]) => `- \`${k}\`: "${text(en[k], 'building')}" (${w.split(' (')[0]})`).join('\n')}

## Story narration

${voRows.some((r) => !r.ok) ? voRows.filter((r) => !r.ok).map((r) => `- **needed** \`${r.file}\` (${r.id})`).join('\n') : 'All story lines used so far are recorded.'}
`;

fs.writeFileSync('docs/read-aloud-script.md', md);
console.log(`Building: ${need.building} needed; Beginning: ${need.beginning} needed; recorded: ${done}. Wrote docs/read-aloud-script.md`);
